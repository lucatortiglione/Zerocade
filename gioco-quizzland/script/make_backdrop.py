"""Writes assets/sfondo.svg, ZeroQuizz's backdrop: a violet night sky with aurora glows,
stars, a ringed planet, big faint question marks and a glowing perspective grid as the
"land" at the bottom. 1080 x 1920 (portrait); the overlay covers the scene with it, so a
landscape scene shows its middle band. Deterministic: the same file every run.

Usage: python script/make_backdrop.py
"""
import math
import os
import random

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
OUT = os.path.join(ROOT, "assets", "sfondo.svg")
W, H = 1080, 1920
HORIZON = 1430
rnd = random.Random(20261103)


def f(x):
    return f"{x:.1f}".rstrip("0").rstrip(".")


def glow(id_, color, opacity):
    return (
        f'<radialGradient id="{id_}"><stop offset="0" stop-color="{color}" stop-opacity="{opacity}"/>'
        f'<stop offset="1" stop-color="{color}" stop-opacity="0"/></radialGradient>'
    )


def stars():
    out = []
    for _ in range(70):
        x, y = rnd.uniform(0, W), rnd.uniform(0, HORIZON - 60)
        r = rnd.choice([1.2, 1.6, 2, 2.4, 3])
        o = rnd.uniform(0.25, 0.8)
        out.append(f'<circle cx="{f(x)}" cy="{f(y)}" r="{r}" fill="#fff" fill-opacity="{o:.2f}"/>')
    # A few four-point sparkles.
    for _ in range(9):
        x, y, s = rnd.uniform(40, W - 40), rnd.uniform(40, HORIZON - 200), rnd.uniform(9, 18)
        k = s * 0.22
        d = (
            f"M{f(x)} {f(y - s)}Q{f(x + k)} {f(y - k)} {f(x + s)} {f(y)}Q{f(x + k)} {f(y + k)} {f(x)} {f(y + s)}"
            f"Q{f(x - k)} {f(y + k)} {f(x - s)} {f(y)}Q{f(x - k)} {f(y - k)} {f(x)} {f(y - s)}Z"
        )
        out.append(f'<path d="{d}" fill="#fff" fill-opacity="{rnd.uniform(0.45, 0.85):.2f}"/>')
    return "\n  ".join(out)


# A question mark centred on 0,0, about 150 tall, drawn as a stroke (no font needed).
QUESTION = (
    '<path d="M-30 -42C-30 -78 30 -78 30 -42C30 -14 0 -12 0 16V24" fill="none" stroke-width="18" '
    'stroke-linecap="round" stroke-linejoin="round"/><circle cx="0" cy="58" r="12" stroke="none"/>'
)


def marks():
    spots = [
        (150, 520, 1.5, -16, "#ff7ad9", 0.16),
        (930, 330, 1.1, 14, "#7fe0ff", 0.14),
        (880, 1120, 1.9, 10, "#b39dff", 0.12),
        (120, 1190, 1.0, -8, "#ffd36b", 0.13),
        (560, 170, 0.7, 4, "#ffffff", 0.1),
    ]
    out = []
    for x, y, s, rot, color, o in spots:
        out.append(
            f'<g transform="translate({x} {y}) rotate({rot}) scale({s})" stroke="{color}" fill="{color}" '
            f'opacity="{o}">{QUESTION}</g>'
        )
    return "\n  ".join(out)


def grid():
    vx = W / 2
    lines = []
    # Lines running to the vanishing point on the horizon.
    for i in range(-14, 15):
        x0 = vx + i * 150
        lines.append(f'<line x1="{f(vx + i * 6)}" y1="{HORIZON}" x2="{f(x0)}" y2="{H}"/>')
    # Cross lines, closer together towards the horizon.
    for k in range(1, 14):
        t = (k / 13) ** 2.2
        y = HORIZON + (H - HORIZON) * t
        lines.append(f'<line x1="0" y1="{f(y)}" x2="{W}" y2="{f(y)}"/>')
    return "\n    ".join(lines)


def main():
    svg = f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" preserveAspectRatio="xMidYMid slice">
  <!-- Generated by script/make_backdrop.py: edit there. -->
  <defs>
    <linearGradient id="sky" x1="0" y1="0" x2="0.3" y2="1">
      <stop offset="0" stop-color="#2c1572"/>
      <stop offset="0.5" stop-color="#1b1052"/>
      <stop offset="0.74" stop-color="#140c3f"/>
      <stop offset="1" stop-color="#0b0826"/>
    </linearGradient>
    {glow("pink", "#ff4fd8", 0.5)}
    {glow("cyan", "#29d3ff", 0.4)}
    {glow("violet", "#8b5cf6", 0.55)}
    {glow("gold", "#ffb03d", 0.32)}
    <linearGradient id="horizon" x1="0" y1="0" x2="1" y2="0">
      <stop offset="0" stop-color="#ff4fd8" stop-opacity="0"/>
      <stop offset="0.5" stop-color="#ff8ae6"/>
      <stop offset="1" stop-color="#29d3ff" stop-opacity="0"/>
    </linearGradient>
    <linearGradient id="floor" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#ff4fd8" stop-opacity="0.15"/>
      <stop offset="1" stop-color="#29d3ff" stop-opacity="0.55"/>
    </linearGradient>
    <linearGradient id="fade" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#fff" stop-opacity="0"/>
      <stop offset="0.35" stop-color="#fff" stop-opacity="0.6"/>
      <stop offset="1" stop-color="#fff"/>
    </linearGradient>
    <mask id="floor-fade"><rect y="{HORIZON}" width="{W}" height="{H - HORIZON}" fill="url(#fade)"/></mask>
    <!-- The front half of the ring, in the ring's own (rotated) frame. -->
    <clipPath id="ring-front"><rect x="700" y="215" width="410" height="60"/></clipPath>
    <radialGradient id="planet" cx="0.35" cy="0.3" r="0.8">
      <stop offset="0" stop-color="#ffb3ec"/>
      <stop offset="0.55" stop-color="#9b5cf6"/>
      <stop offset="1" stop-color="#3b1d8f"/>
    </radialGradient>
  </defs>
  <rect width="{W}" height="{H}" fill="url(#sky)"/>
  <ellipse cx="120" cy="300" rx="640" ry="540" fill="url(#pink)"/>
  <ellipse cx="1010" cy="820" rx="620" ry="580" fill="url(#cyan)"/>
  <ellipse cx="380" cy="1300" rx="760" ry="520" fill="url(#violet)"/>
  <ellipse cx="540" cy="{HORIZON}" rx="720" ry="200" fill="url(#gold)"/>
  {stars()}
  <g opacity="0.6" transform="rotate(-18 905 215)">
    <ellipse cx="905" cy="215" rx="190" ry="34" fill="none" stroke="#ffd1f4" stroke-opacity="0.4" stroke-width="5"/>
    <circle cx="905" cy="215" r="92" fill="url(#planet)"/>
    <ellipse cx="905" cy="215" rx="190" ry="34" fill="none" stroke="#ffd1f4" stroke-opacity="0.9" stroke-width="5" clip-path="url(#ring-front)"/>
  </g>
  {marks()}
  <rect y="{HORIZON}" width="{W}" height="{H - HORIZON}" fill="#0b0826" fill-opacity="0.55"/>
  <g mask="url(#floor-fade)" stroke="url(#floor)" stroke-width="2.5">
    {grid()}
  </g>
  <rect y="{HORIZON - 2}" width="{W}" height="4" fill="url(#horizon)"/>
  <ellipse cx="540" cy="{HORIZON}" rx="520" ry="16" fill="#ff8ae6" fill-opacity="0.18"/>
</svg>
"""
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(svg)
    print(f"{OUT} ({len(svg) // 1024} KB)")


if __name__ == "__main__":
    main()
